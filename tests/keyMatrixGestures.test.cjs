const assert = require('node:assert/strict');
const { mkdtempSync, rmSync, writeFileSync } = require('node:fs');
const { tmpdir } = require('node:os');
const { join, resolve } = require('node:path');
const { buildSync } = require('esbuild');
const { JSDOM } = require('jsdom');
(async () => {
  const dir = mkdtempSync(join(tmpdir(), 'key-gestures-'));
  const dom = new JSDOM('<!doctype html><div id="root"></div>', { url: 'http://localhost/' });
  global.window = dom.window; global.document = dom.window.document; global.navigator = dom.window.navigator;
  global.IS_REACT_ACT_ENVIRONMENT = true;
  const oldChannel = global.MessageChannel;
  global.MessageChannel = class { constructor() { this.port1 = { onmessage: null }; this.port2 = { postMessage: () => setTimeout(() => this.port1.onmessage?.(), 0) }; } };
  try {
    const entry = join(dir, 'entry.tsx');
    writeFileSync(entry, `import React, { act } from ${JSON.stringify(resolve('node_modules/react/index.js'))};
import { createRoot } from ${JSON.stringify(resolve('node_modules/react-dom/client.js'))};
import { KeyMatrix } from ${JSON.stringify(resolve('src/components/KeyMatrix.tsx'))};
export { act }; export function create(el) { const root = createRoot(el); return { render: (keys, select, trigger) => root.render(<KeyMatrix keys={keys} selectedKeyIndex={0} onSelectKey={select} onTriggerAction={trigger}/>), unmount: () => root.unmount() }; }`);
    const out = join(dir, 'bundle.cjs');
    buildSync({ entryPoints: [entry], outfile: out, bundle: true, platform: 'node', format: 'cjs', logLevel: 'silent', nodePaths: [resolve('node_modules')] });
    const { act, create } = require(out); const ui = create(document.getElementById('root'));
    const action = id => ({ id, name: id, category: 'hotkey', payload: { keys: ['A'] } });
    const key = { keyIndex: 0, label: 'Key', iconName: 'icons', tapAction: action('tap'), holdAction: action('hold'), doubleTapAction: action('double') };
    const events = [], selections = [];
    const render = async k => act(async () => ui.render([k], v => selections.push(v), id => events.push(id)));
    const button = () => document.querySelector('.macropad-key');
    const keyboard = async (type, repeat = false) => act(async () => button().dispatchEvent(new window.KeyboardEvent(type, { key: ' ', bubbles: true, cancelable: true, repeat })));
    const wait = async ms => act(async () => { await new Promise(resolve => setTimeout(resolve, ms)); });
    const pointer = async type => act(async () => {
      const event = new window.MouseEvent(type, { bubbles: true, button: 0, clientX: 0, clientY: 0 });
      Object.defineProperty(event, 'pointerId', { value: 3 }); button().dispatchEvent(event);
    });
    await render(key);
    await keyboard('keydown'); await keyboard('keyup'); await wait(250);
    assert.deepEqual(events.splice(0), ['tap']); assert(selections.length, 'keyboard selects the key');
    await keyboard('keydown'); await keyboard('keydown', true); await wait(280); await keyboard('keyup'); await wait(250);
    assert.deepEqual(events.splice(0), ['hold'], 'a completed hold never also fires tap');
    await keyboard('keydown'); await keyboard('keyup'); await keyboard('keydown'); await keyboard('keyup'); await wait(250);
    assert.deepEqual(events.splice(0), ['double']);
    await render({ ...key, doubleTapAction: null });
    await keyboard('keydown'); await keyboard('keyup'); await keyboard('keydown'); await keyboard('keyup');
    assert.deepEqual(events.splice(0), ['tap', 'tap'], 'rapid taps without a double binding each fire');
    await render(key);
    await pointer('pointerdown'); await pointer('pointercancel'); await wait(300);
    assert.deepEqual(events.splice(0), [], 'pointer cancellation never triggers an action');
    await pointer('pointerdown');
    await act(async () => { const e = new window.MouseEvent('pointermove', { bubbles: true, clientX: 50, clientY: 50 }); Object.defineProperty(e, 'pointerId', { value: 3 }); window.dispatchEvent(e); });
    await wait(300); assert.deepEqual(events.splice(0), [], 'window movement cancels even without pointer capture');
    await pointer('pointerdown'); await act(async () => window.dispatchEvent(new window.Event('blur'))); await wait(300);
    assert.deepEqual(events.splice(0), [], 'losing window focus cancels a pending hold');
    await pointer('pointerdown'); await pointer('pointerout'); await wait(300);
    assert.deepEqual(events.splice(0), [], 'pointer leave cancels rather than activating');
    const safety = { ...key, iconName: 'createLucideIcon', isDestructiveSafety: true, safetyConfirmAction: action('confirm'), longPressThresholdMs: 80 };
    await render(safety); await keyboard('keydown'); await keyboard('keyup');
    assert.deepEqual(events.splice(0), ['safety-aborted']);
    await keyboard('keydown'); await wait(100); await keyboard('keyup'); await wait(240);
    assert.deepEqual(events.splice(0), ['confirm'], 'completed safety hold fires once');
    await render(key); await keyboard('keydown'); await keyboard('keyup'); await render({ ...key, label: 'Other layer' }); await wait(250);
    assert.deepEqual(events.splice(0), [], 'a pending tap does not fire after layer changes');
    await act(async () => ui.unmount());
    console.log('keyMatrixGestures: hold isolation, cancellation, keyboard, double tap, safety and layer changes passed');
  } finally { global.MessageChannel = oldChannel; dom.window.close(); rmSync(dir, { recursive: true, force: true }); }
})().catch(err => { console.error(err); process.exitCode = 1; });
