const assert = require('node:assert/strict');
const { readFileSync } = require('node:fs');
const { join } = require('node:path');
const { JSDOM } = require('jsdom');
const root = join(__dirname, '..');
const html = readFileSync(join(root, 'website/index.html'), 'utf8');
const bundle = readFileSync(join(root, 'website/assets/specular-button.js'), 'utf8');
const dom = new JSDOM(html, { url: 'https://example.test/', runScripts: 'outside-only', pretendToBeVisual: true });
const { window } = dom;
const fallback = window.document.querySelector('.hero-download-mount a');
assert.equal(fallback.href, 'https://github.com/david-8837/MacroPad-/releases/download/v1.0.0-test.1/ZERO-Deck-Studio-1.0.0-x64.exe', 'the static fallback is a real link');
let webglAttempts = 0;
window.HTMLCanvasElement.prototype.getContext = type => { if (type === 'webgl2') webglAttempts++; return null; }; // WebGL is optional.
window.matchMedia = () => ({ matches: true, addEventListener() {} });
window.eval(bundle);
const link = window.document.querySelector('.hero-download-mount a');
assert.ok(link.classList.contains('specular-button'), 'React enhances the native link');
assert.equal(link.href, fallback.href);
assert.equal(link.target, '_top');
assert.equal(link.getAttribute('aria-describedby'), 'hero-download-status');
assert.match(link.textContent, /download for windows/i);
assert.equal(link.querySelector('canvas').getAttribute('aria-hidden'), 'true');
assert.match(window.document.querySelector('#hero-download-status').textContent, /unsigned Windows test build/i);
assert.equal(link.getAttribute('role'), null, 'the download remains a native link');
assert.equal(webglAttempts, 0, 'shader setup does not block the initial page load');
link.getBoundingClientRect = () => ({ left: 400, right: 600, top: 400, bottom: 450 });
window.dispatchEvent(new window.MouseEvent('pointermove', { clientX: 0, clientY: 0 }));
assert.equal(webglAttempts, 0, 'distant pointer activity does not initialize the effect');
window.dispatchEvent(new window.MouseEvent('pointermove', { clientX: 410, clientY: 410 }));
assert.equal(webglAttempts, 1, 'approaching the button initializes the optional WebGL effect');
window.dispatchEvent(new window.MouseEvent('pointermove', { clientX: 415, clientY: 415 }));
assert.equal(webglAttempts, 1, 'unavailable WebGL is not retried on every pointer move');
dom.window.close();
console.log('website specular button: React enhancement, static and no-WebGL fallbacks passed');
