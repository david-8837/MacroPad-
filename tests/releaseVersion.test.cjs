'use strict';
const assert = require('node:assert/strict');
const { readFileSync } = require('node:fs');
const { join } = require('node:path');
const semver = require('semver');
const { validateReleaseVersion } = require('../scripts/check-release-version.cjs');
const lock = version => ({version, packages:{'':{version}}});
assert.equal(validateReleaseVersion('1.0.1-test.5',lock('1.0.1-test.5'),['v1.0.1-test.3','v1.0.1-test.4']), '1.0.1-test.4');
assert.equal(validateReleaseVersion('1.0.1-test.10',lock('1.0.1-test.10'),['v1.0.1-test.9']), '1.0.1-test.9', 'compare numeric prerelease versions, not strings');
assert.throws(()=>validateReleaseVersion('1.0.1-test.4',lock('1.0.1-test.4'),['v1.0.1-test.4']),/not newer/);
assert.throws(()=>validateReleaseVersion('1.0.1-test.3',lock('1.0.1-test.3'),['v1.0.1-test.4']),/not newer/);
assert.throws(()=>validateReleaseVersion('1.0.1-test.5',lock('1.0.1-test.4'),[]),/do not match/);
assert.throws(()=>validateReleaseVersion('invalid',lock('invalid'),[]),/Invalid app version/);
assert.throws(()=>validateReleaseVersion('1.0.1-test.99',lock('1.0.1-test.99'),['v1.0.1']),/not newer/, 'a prerelease cannot replace an existing stable version');
assert.equal(validateReleaseVersion('1.0.2-test.0',lock('1.0.2-test.0'),['v1.0.1','not-a-version']), '1.0.1');
assert.equal(semver.inc('1.0.1-test.4','prerelease','test'),'1.0.1-test.5');
const pkg = require('../package.json');
assert.equal(pkg.scripts['version:next-test'], 'npm version prerelease --preid=test --no-git-tag-version');
const currentLock = require('../package-lock.json');
assert.equal(currentLock.version, pkg.version); assert.equal(currentLock.packages[''].version, pkg.version);
const workflow = readFileSync(join(__dirname, '../.github/workflows/windows-test-installer.yml'), 'utf8');
assert.match(workflow, /if: github\.event_name == 'push' && contains\(github\.event\.head_commit\.message, '\[publish-test-installer\]'\)/);
assert.match(workflow, /GH_TOKEN: \${{ github\.token }}/);
assert(workflow.indexOf('node scripts/check-release-version.cjs') < workflow.indexOf('Package Windows installer'), 'reject reused versions before packaging');
console.log('release version: bumps, semantic ordering, duplicate protection and lockfile checks passed');
