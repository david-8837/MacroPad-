const assert = require('node:assert/strict');
const { mkdtempSync, rmSync, writeFileSync } = require('node:fs');
const { tmpdir } = require('node:os');
const { join, resolve } = require('node:path');
const { buildSync } = require('esbuild');
const { JSDOM } = require('jsdom');
(async () => {
  const dir = mkdtempSync(join(tmpdir(), 'zero-settings-'));
  const dom = new JSDOM('<!doctype html><div id="root"></div>', { url: 'http://localhost/' });
  global.window = dom.window; global.document = dom.window.document; global.navigator = dom.window.navigator;
  global.IS_REACT_ACT_ENVIRONMENT = true;
  const oldChannel = global.MessageChannel;
  global.MessageChannel = class { constructor() { this.port1 = { onmessage: null }; this.port2 = { postMessage: () => setTimeout(() => this.port1.onmessage?.(), 0) }; } };
  window.matchMedia = () => ({ matches: false });
  try {
    const entry = join(dir, 'entry.tsx');
    writeFileSync(entry, `import React, {act} from ${JSON.stringify(resolve('node_modules/react/index.js'))};
      import {createRoot} from ${JSON.stringify(resolve('node_modules/react-dom/client.js'))};
      import {SettingsPage} from ${JSON.stringify(resolve('src/components/SettingsPage.tsx'))};
      export {act}; export function create(el) { const root = createRoot(el); return {render: props => root.render(<SettingsPage {...props}/>), unmount: () => root.unmount()}; }`);
    const out = join(dir, 'bundle.cjs');
    buildSync({ entryPoints: [entry], outfile: out, bundle: true, platform: 'node', format: 'cjs', logLevel: 'silent', nodePaths: [resolve('node_modules')] });
    const { act, create } = require(out), ui = create(document.getElementById('root'));
    let factor = 1, fail = false, safe = false, theme = 'light', intro = true, backups = 0, welcomes = 0;
    const props = () => ({ theme, onThemeChange: next => { theme = next; }, openingAnimation: intro, onOpeningAnimationChange: next => { intro = next; }, preferenceNotice: '', safePreview: safe, onSafePreviewChange: next => { safe = next; }, backupPanel: 'Backup tools', onReset: () => backups++, onOpenWelcome: () => welcomes++, onReplayIntro: () => {}, onOpenHelp: () => {} });
    window.electronAPI = { getViewScale: async () => factor, setViewScale: async f => { if (fail) throw Error('failure'); factor = f; return f; } };
    const render = () => act(async () => ui.render(props()));
    const clickText = async text => act(async () => [...document.querySelectorAll('button')].find(b => b.textContent.includes(text)).click());
    await render();
    await act(async () => document.querySelector('input[value=dark]').click()); assert.equal(theme, 'dark');
    await act(async () => document.querySelector('[role=switch][aria-label="Opening animation"]').click()); assert.equal(intro, false);
    await render();
    assert.equal(document.querySelector('input[value=dark]').checked, true);
    assert.equal(document.querySelector('[role=switch][aria-label="Opening animation"]').getAttribute('aria-checked'), 'false');
    const select = document.querySelector('#settings-view-size');
    assert.equal(select.value, '100');
    await act(async () => { select.value = '125'; select.dispatchEvent(new window.Event('change', { bubbles: true })); });
    assert.equal(factor, 1.25); assert.equal(select.value, '125');
    await clickText('Reset to 100%'); assert.equal(factor, 1); assert.equal(select.value, '100');
    fail = true;
    await act(async () => { select.value = '150'; select.dispatchEvent(new window.Event('change', { bubbles: true })); });
    assert.equal(select.value, '100'); assert.match(document.body.textContent, /Could not change the view size/);
    await act(async () => document.querySelector('[role="switch"][aria-label="Safe preview"]').click()); assert.equal(safe, true);
    await render(); assert.equal(document.querySelector('[role="switch"][aria-label="Safe preview"]').getAttribute('aria-checked'), 'true');
    assert.match(document.body.textContent, /Backup tools/); await clickText('Welcome & tour');
    assert.equal(backups, 0); assert.equal(welcomes, 1);
    await clickText('Reset saved data');
    const confirm = document.querySelector('#reset-confirmation');
    assert(document.querySelector('button:disabled') || confirm);
    await act(async () => { const setter = Object.getOwnPropertyDescriptor(window.HTMLInputElement.prototype, 'value').set; setter.call(confirm, 'RESET'); confirm.dispatchEvent(new window.Event('input', { bubbles: true })); });
    await clickText('Delete saved data'); assert.equal(backups, 1);
    await act(async () => ui.unmount());
    delete window.electronAPI;
    const browserUi = create(document.getElementById('root'));
    await act(async () => browserUi.render(props()));
    assert.equal(document.querySelector('#settings-view-size').disabled, true);
    assert.match(document.body.textContent, /available in the ZERO desktop app/);
    await act(async () => browserUi.unmount());
    console.log('settings UI: scale, failure, preview, actions and desktop-only fallback passed');
  } finally { global.MessageChannel = oldChannel; dom.window.close(); rmSync(dir, { recursive: true, force: true }); }
})().catch(error => { console.error(error); process.exitCode = 1; });
