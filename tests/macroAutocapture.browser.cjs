// Optional: start Vite and provide CHROMIUM_PATH/PUPETEER_CORE_PATH.
const assert = require('node:assert/strict');
const puppeteer = require(process.env.PUPPETEER_CORE_PATH || 'puppeteer-core');
(async () => {
  const browser = await puppeteer.launch({executablePath:process.env.CHROMIUM_PATH,headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
  try {
    const context=await browser.createBrowserContext(), page=await context.newPage(), errors=[];
    page.on('pageerror',e=>errors.push(String(e)));
    await page.setViewport({width:1440,height:1000});
    await page.emulateMediaFeatures([{name:'prefers-reduced-motion',value:'reduce'}]);
    await page.evaluateOnNewDocument(()=>localStorage.setItem('kadowaz_guide_seen','1'));
    await page.goto(process.env.APP_URL || 'http://127.0.0.1:5173/',{waitUntil:'load'});
    await page.click('nav[aria-label="Modules"] button::-p-text(Macros)');
    await page.waitForSelector('[aria-label="Type the keys you want to log"]');
    await page.waitForFunction(()=>document.activeElement?.getAttribute('aria-label') === 'Type the keys you want to log');
    const actions = async slot => JSON.parse(await page.evaluate(()=>localStorage.getItem('kadowaz_macros_v2')))[slot].actions;
    await page.keyboard.press('a'); await page.keyboard.press('Space'); await page.keyboard.press('Enter');
    await page.waitForFunction(()=>JSON.parse(localStorage.getItem('kadowaz_macros_v2'))[0].actions.length === 3);
    assert.deepEqual((await actions(0)).map(a=>a.keys), [['A'],['Space'],['Enter']], 'opening Macros is immediately ready for laptop input');
    const slot1 = await page.$('button::-p-text(M1)'); await slot1.click();
    await page.waitForFunction(()=>document.activeElement?.getAttribute('aria-label') === 'Type the keys you want to log');
    await page.keyboard.press('b');
    await page.waitForFunction(()=>JSON.parse(localStorage.getItem('kadowaz_macros_v2'))[1].actions.length === 1);
    assert.deepEqual((await actions(1))[0].keys,['B'], 'slot change remains ready');
    await page.click('button::-p-text(Win + next key)'); await page.keyboard.press('r');
    await page.waitForFunction(()=>JSON.parse(localStorage.getItem('kadowaz_macros_v2'))[1].actions.length === 2);
    assert.deepEqual((await actions(1))[1].keys,['Win','R']);
    await page.click('[aria-label="Key Ctrl"]'); await page.keyboard.press('c');
    await page.waitForFunction(()=>JSON.parse(localStorage.getItem('kadowaz_macros_v2'))[1].actions.length === 3);
    assert.deepEqual((await actions(1))[2].keys,['Ctrl','C'], 'virtual modifier combines with laptop key');
    const label = 'input[placeholder^="Enter macro label"]';
    await page.click(label); await page.type(label,'My setup');
    assert.equal(await page.$eval(label,e=>e.value),'My setup');
    assert.equal((await actions(1)).length,3,'typing a macro name does not record keys');
    await page.click('button[title^="Saves the macro library"]'); await page.keyboard.press('x');
    await page.waitForFunction(()=>JSON.parse(localStorage.getItem('kadowaz_macros_v2'))[1].actions.length === 4);
    assert.deepEqual((await actions(1))[3].keys,['X'], 'mouse actions return to ready state');
    await page.focus('button[title^="Saves the macro library"]'); await page.keyboard.press('Space');
    assert.equal((await actions(1)).length,4,'keyboard button activation does not record Space');
    await page.focus('[aria-label="Key A"]'); await page.keyboard.press('Enter');
    await page.waitForFunction(()=>JSON.parse(localStorage.getItem('kadowaz_macros_v2'))[1].actions.length === 5);
    assert.deepEqual((await actions(1))[4].keys,['A'], 'keyboard activation of on-screen keys stays accessible');
    await page.keyboard.down('Control');await page.keyboard.press('k');await page.keyboard.up('Control');
    await page.waitForSelector('[aria-label="Global Command Palette"]');
    await page.type('[aria-label="Search commands"]','settings');
    assert.equal((await actions(1)).length,5,'command palette is not captured');
    await page.keyboard.press('Escape');
    await page.click('button::-p-text(Text String)'); await page.type('input[placeholder^="e.g. git status"]','hello');
    assert.equal((await actions(1)).length,5,'other builder tabs do not record');
    await page.click('button::-p-text(Type Keys)');
    await page.waitForFunction(()=>document.activeElement?.getAttribute('aria-label') === 'Type the keys you want to log');
    await page.keyboard.press('z'); await page.waitForFunction(()=>JSON.parse(localStorage.getItem('kadowaz_macros_v2'))[1].actions.length === 6);
    await page.click('button[aria-label="Help & About"]'); await page.waitForSelector('[aria-labelledby="help-title"]');
    await page.keyboard.press('y'); assert.equal((await actions(1)).length,6,'modal input is not captured');
    await page.click('button[aria-label="Close help"]');
    await page.click('nav[aria-label="Modules"] button::-p-text(Keys)'); await page.waitForSelector('.designer-layout');
    await page.keyboard.press('q'); assert.equal((await actions(1)).length,6,'leaving Macros stops recording');
    assert.deepEqual(errors,[]);
    await context.close(); console.log('macro auto-capture: ready on entry and slot change; fields, controls, modal and navigation protected');
  } finally { await browser.close(); }
})().catch(e=>{console.error(e);process.exitCode=1});
