const assert = require('node:assert/strict');
const { buildSync } = require('esbuild');
const { resolve } = require('node:path');
const result = buildSync({ stdin: { contents: `export * from './src/oled/customScreen';`, resolveDir: resolve(__dirname, '..'), loader: 'ts' }, bundle: true, platform: 'node', format: 'cjs', write: false, logLevel: 'silent' });
const mod = { exports: {} }; new Function('module','exports',result.outputFiles[0].text)(mod, mod.exports);
const { screenCrop, rgbaToPages, encodePages, decodePages, isCustomScreen } = mod.exports;
assert.deepEqual(screenCrop(400, 400, 1, .5, .5), { x: 0, y: 150, w: 400, h: 100 });
assert.deepEqual(screenCrop(400, 400, 2, 0, 1), { x: 0, y: 350, w: 200, h: 50 });
assert.throws(() => screenCrop(0, 1, 1, 0, 0));
const pixels = new Uint8ClampedArray(128*32*4); pixels[0]=255; pixels[1]=255; pixels[2]=255; pixels[3]=255;
const i = (8 * 128 + 127) * 4; pixels[i]=pixels[i+1]=pixels[i+2]=pixels[i+3]=255;
const pages = rgbaToPages(pixels,128,false);
assert.equal(pages[0],1); assert.equal(pages[128+127],1); assert.equal(pages.reduce((a,b)=>a+b,0),2);
const inverted = rgbaToPages(pixels,128,true); assert.equal(inverted[0],254); assert.equal(inverted[255],254);
const encoded = encodePages(pages); assert.deepEqual(decodePages(encoded), pages);
assert(isCustomScreen({kind:'drawing',name:'Draw',fps:5,frames:[encoded]}));
assert(!isCustomScreen({kind:'video',name:'x',fps:5,frames:Array(51).fill(encoded)}));
assert(!isCustomScreen({kind:'image',name:'x',fps:5,frames:['invalid']}));
assert.throws(()=>decodePages('bad'));
console.log('custom screen: crop, monochrome pixels, frame codec and bounded validation passed');
