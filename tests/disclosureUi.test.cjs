// Inspector disclosures animate without losing native summary semantics or hiding content mid-collapse.
const assert = require('node:assert/strict');
const { readFileSync } = require('node:fs');
const { resolve } = require('node:path');
const read = path => readFileSync(resolve(path), 'utf8');
const app = read('src/App.tsx');
const component = read('src/components/AnimatedDetails.tsx');
const firmware = read('src/components/FirmwarePanel.tsx');
const hardware = read('src/components/HardwareDiagnosticsPanel.tsx');
const css = read('src/index.css');
assert.equal((app.match(/<AnimatedDetails\b/g) || []).length, 4);
for (const heading of ['Hardware Status &amp; Diagnostics', 'Audio mixer', 'Webhook API']) assert(app.includes(heading));
assert.match(app, /onOpenChange=\{setIsHardwareDiagnosticsExpanded\}/);
assert.match(app, /onOpenChange=\{setIsFirmwareExpanded\}/);
assert.match(app, /<FirmwarePanel isExpanded=\{isFirmwareExpanded\} keepVisible=\{renderedOpen\}/);
assert.match(firmware, /if \(!isExpanded && !keepVisible\) return null/);
assert.match(app, /keepVisible=\{renderedOpen\}/);
assert.match(hardware, /if \(!isExpanded && !keepVisible\) return null/);
assert.doesNotMatch(hardware, /Export Report|exportFullDiagnosticReport/);
assert.match(hardware, /Copy Timeline to Clipboard/);
assert.match(hardware, /Copy Log/);
assert.match(component, /<details ref=\{ref\}[\s\S]*?open=\{renderedOpen\}/);
assert.match(component, /<summary[^>]+aria-expanded=\{open\}[^>]+onClick=\{toggle\}/);
assert.match(component, /bodyRef\.current\.inert = !open/);
assert.match(component, /aria-hidden=\{!open\}/);
assert.match(component, /setTimeout\(\(\) => setRenderedOpen\(false\), 340\)/);
assert.match(component, /clearTimeout\(timer\)/);
assert.match(component, /prefers-reduced-motion: reduce/);
assert.match(css, /grid-template-rows: minmax\(0, 0fr\)/);
assert.match(css, /\.disclosure-body--open \{ grid-template-rows: minmax\(0, 1fr\)/);
assert.match(css, /@media \(prefers-reduced-motion: reduce\) \{\s*\.disclosure-body \{ transition: none/);
console.log('disclosureUi: accessible, reversible inspector animations and reduced motion are present');
