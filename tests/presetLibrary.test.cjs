const assert = require('node:assert/strict');
const { mkdtempSync, rmSync, writeFileSync } = require('node:fs');
const { tmpdir } = require('node:os');
const { join, resolve } = require('node:path');
const { build } = require('esbuild');
(async () => {
  const dir = mkdtempSync(join(tmpdir(), 'preset-library-'));
  try {
    const root = resolve(__dirname, '..');
    const entry = join(dir, 'entry.mjs');
    writeFileSync(entry, `export * from '${root}/src/utils/presetLibrary.ts';\nexport { LAYER_PRESETS, applyLayerPreset } from '${root}/src/data/layerPresets.ts';\nexport { defaultDeck } from '${root}/src/data/defaultDeck.ts';\nexport { deckToConfig } from '${root}/src/utils/deckToConfig.ts';\nexport { defaultConfig, ACTION_TYPE } from '${root}/host/protocol/mpad3-protocol.mjs';`);
    const output = join(dir, 'bundle.mjs');
    await build({ entryPoints: [entry], bundle: true, platform: 'node', format: 'esm', outfile: output, logLevel: 'silent' });
    const m = await import(`file://${output}`);
    let raw = null;
    const storage = { getItem() { return raw; }, setItem(_key, value) { raw = value; } };
    let library = m.readPresetLibrary(storage).library;
    for (const original of m.LAYER_PRESETS) { m.writePresetLibrary(storage, m.savePreset(library, original)); assert.equal(m.readPresetLibrary(storage).error, null, `valid built-in override: ${original.id}`); }
    raw = null;
    let custom = m.createPreset('custom-example'); custom.name = 'My layout'; custom.iconId = 'blender';
    assert.equal(custom.keys.length, 9); assert(custom.keys.every(k => k.action === null));
    const key = m.keyToBinding(custom.keys[0], 0); key.label = 'Copy'; key.sublabel = 'Ctrl + C'; key.iconName = 'Copy';
    key.holdAction = { id:'hold', category:'hotkey', name:'Hold', payload:{keys:['H']} };
    key.doubleTapAction = { id:'double', category:'hotkey', name:'Double', payload:{keys:['D']} };
    key.isDestructiveSafety = true; key.longPressThresholdMs = 1200;
    key.safetyConfirmAction = { id:'safe', category:'hotkey', name:'Confirm', payload:{keys:['S']} };
    key.tapAction = { id: 'test', category: 'hotkey', name: 'Copy', payload: { keys: ['Ctrl', 'C'] } };
    custom.keys[0] = m.bindingToKey(key);
    library = m.savePreset(library, custom); m.writePresetLibrary(storage, library);
    assert.equal(m.readPresetLibrary(storage).error, null);
    library = m.readPresetLibrary(storage).library;
    assert.equal(library.custom[0].iconId, 'blender');
    let deck = structuredClone(m.defaultDeck); const before = structuredClone(deck);
    deck.layers[2] = m.applyLayerPreset(deck.layers[2], library.custom[0]);
    assert.deepEqual(deck.layers[2].keys[0].tapAction.payload.keys, ['Ctrl', 'C']);
    assert.equal(deck.layers[2].keys[0].holdAction.name, 'Hold'); assert.equal(deck.layers[2].keys[0].doubleTapAction.name, 'Double');
    assert.equal(deck.layers[2].keys[0].safetyConfirmAction.name, 'Confirm'); assert.equal(deck.layers[2].keys[0].longPressThresholdMs, 1200);
    assert(deck.layers[2].keys.slice(1).every(k => k.tapAction === null));
    assert.deepEqual(deck.layers[2].dial, before.layers[2].dial);
    assert.deepEqual(deck.layers[0], before.layers[0]);
    deck.layers[2].keys[0].holdAction = null; deck.layers[2].keys[0].doubleTapAction = null; deck.layers[2].keys[0].isDestructiveSafety = false; deck.layers[2].keys[0].safetyConfirmAction = null;
    let {config, unsupported} = m.deckToConfig(deck, m.defaultConfig());
    assert.deepEqual(unsupported, []); assert.notEqual(config.channels[2].keys[0].type, m.ACTION_TYPE.NONE);
    assert(config.channels[2].keys.slice(1).every(k => k.type === m.ACTION_TYPE.NONE));
    deck.layers[2].keys[0].tapAction.payload.keys[1] = 'X';
    assert.deepEqual(library.custom[0].keys[0].action.payload.keys, ['Ctrl','C'], 'layers do not mutate saved presets');
    let edited = structuredClone(m.LAYER_PRESETS.find(p => p.id === 'blender'));
    edited.keys[0] = m.bindingToKey({ ...m.keyToBinding(edited.keys[0], 0), label: 'Custom move', tapAction: { id:'x',category:'hotkey',name:'Move',payload:{keys:['H']} } });
    library = m.savePreset(library, edited); m.writePresetLibrary(storage, library);
    let loaded = m.readPresetLibrary(storage); assert.equal(loaded.error, null);
    assert.equal(m.allPresets(loaded.library).find(p => p.id === 'blender').keys[0].label, 'Custom move');
    library = m.removePreset(loaded.library, 'blender');
    assert.equal(m.allPresets(library).find(p => p.id === 'blender').keys[0].label, 'Move');
    assert.deepEqual(edited.keys[0].action.payload.keys, ['H']);
    library = m.removePreset(library, 'custom-example'); assert.equal(library.custom.length, 0);
    let invalid = structuredClone(custom); invalid.keys[0].action.payload.command = 7; raw = JSON.stringify({version:1,overrides:{},custom:[invalid]}); assert(m.readPresetLibrary(storage).error);
    raw = '{bad json'; assert(m.readPresetLibrary(storage).error); assert.equal(raw, '{bad json');
    raw = JSON.stringify({ version:1, overrides:{blender:{id:'blender'}}, custom:[] }); assert(m.readPresetLibrary(storage).error);
    const throwing = {setItem(){throw new Error('quota')}}; assert.throws(() => m.writePresetLibrary(throwing, library), /quota/);
    console.log('presetLibrary: create/edit/restore/delete, roundtrip, blank keys, layer isolation and storage failure passed');
  } finally { rmSync(dir, { recursive:true, force:true }); }
})().catch(e => { console.error(e); process.exitCode = 1; });
