/*
 * dump_layout.c — prints the REAL compiled struct layout as JSON.
 *
 * Built and run by `make -f Makefile.host layout`, which writes
 * firmware/build-host/layout.json. host/tests/run.mjs then compares that file
 * against host/protocol/protocol.json field by field.
 *
 * This is the drift guard. sizeof() and offsetof() are asked of the compiler
 * rather than restated by hand, so if someone adds a field to cfg_channel_t and
 * forgets to update the protocol spec, a test fails instead of the app silently
 * writing its colour settings into the middle of a key binding.
 */
#include <stddef.h>
#include <stdio.h>

#include "config.h"
#include "leds.h"
#include "events.h"
#include "magic.h"
#include "oled_playlist.h"
#include "oled_stream.h"
#include "protocol.h"
#include "storage.h"

/* Stringify the struct name so the JSON says "cfg_action_t" without the call
 * site having to spell it twice. Two-level macro because # does not expand its
 * argument, and the ## paste must happen before stringification. */
#define FIELD_STR2(x) #x
#define FIELD(struct_name, json_name, member)                                       \
    printf("      { \"struct\": \"%s\", \"name\": \"%s\", \"offset\": %zu },\n",     \
           FIELD_STR2(struct_name##_t), json_name, offsetof(struct_name##_t, member))

int main(void) {
    printf("{\n");
    printf("  \"$comment\": \"generated by make -f Makefile.host layout; do not edit\",\n");
    printf("  \"sizes\": {\n");
    printf("    \"action\": %zu,\n", sizeof(cfg_action_t));
    printf("    \"lighting\": %zu,\n", sizeof(cfg_lighting_t));
    printf("    \"channel\": %zu,\n", sizeof(cfg_channel_t));
    printf("    \"global\": %zu,\n", sizeof(cfg_global_t));
    printf("    \"config\": %zu,\n", sizeof(cfg_blob_t));
    printf("    \"sectorHeader\": %zu,\n", sizeof(sector_header_t));
    printf("    \"keyEvent\": %zu,\n", sizeof(key_event_t));
    printf("    \"oledFrameChunk\": %zu,\n", sizeof(oled_stream_chunk_t));
    printf("    \"oledState\": %zu,\n", sizeof(oled_state_t));
    printf("    \"info\": %d,\n", INFO_SIZE);
    printf("    \"chunkSize\": %d,\n", CFG_CHUNK_SIZE);
    printf("    \"chunkCount\": %d\n", (int)CFG_CHUNK_COUNT);
    printf("  },\n");

    printf("  \"offsets\": [\n");
    /* action */
    FIELD(cfg_action, "type", type);
    FIELD(cfg_action, "flags", flags);
    FIELD(cfg_action, "code", code);
    FIELD(cfg_action, "text", text);
    FIELD(cfg_action, "pad", _pad);
    /* lighting */
    FIELD(cfg_lighting, "mode", mode);
    FIELD(cfg_lighting, "brightness", brightness);
    FIELD(cfg_lighting, "speed", speed);
    FIELD(cfg_lighting, "r", r);
    FIELD(cfg_lighting, "g", g);
    FIELD(cfg_lighting, "b", b);
    FIELD(cfg_lighting, "pad0", _pad0);
    FIELD(cfg_lighting, "perKeyMask", per_key_mask);
    FIELD(cfg_lighting, "perKey", per_key);
    FIELD(cfg_lighting, "pad", _pad);
    /* channel */
    FIELD(cfg_channel, "keys", keys);
    FIELD(cfg_channel, "knobCw", knob_cw);
    FIELD(cfg_channel, "knobCcw", knob_ccw);
    FIELD(cfg_channel, "knobTap", knob_tap);
    FIELD(cfg_channel, "knobHold", knob_hold);
    FIELD(cfg_channel, "lighting", lighting);
    /* global */
    FIELD(cfg_global, "holdMs", hold_ms);
    FIELD(cfg_global, "doubleTapMs", double_tap_ms);
    FIELD(cfg_global, "knobHoldMs", knob_hold_ms);
    FIELD(cfg_global, "knobIdleMs", knob_idle_ms);
    FIELD(cfg_global, "knobBatch", knob_batch);
    FIELD(cfg_global, "holdRepeatMs", hold_repeat_ms);
    FIELD(cfg_global, "bootChannel", boot_channel);
    FIELD(cfg_global, "ledInvertOutput", led_invert_output);
    FIELD(cfg_global, "usbReportEvents", usb_report_events);
    FIELD(cfg_global, "oledAutoCycleS", oled_auto_cycle_s);
    FIELD(cfg_global, "oledPlaylist", oled_playlist);
    FIELD(cfg_global, "oledBootMode", oled_boot_mode);
    FIELD(cfg_global, "oledContrast", oled_contrast);
    FIELD(cfg_global, "oledInverted", oled_inverted);
    FIELD(cfg_global, "oledPad", _oled_pad);
    /* config */
    FIELD(cfg_blob, "magic", magic);
    FIELD(cfg_blob, "version", version);
    FIELD(cfg_blob, "length", length);
    FIELD(cfg_blob, "global", global);
    FIELD(cfg_blob, "channels", channels);
    FIELD(cfg_blob, "crc32", crc32);
    /* sector header */
    FIELD(sector_header, "magic", magic);
    FIELD(sector_header, "seq", seq);
    FIELD(sector_header, "blobCrc", blob_crc);
    FIELD(sector_header, "hdrCrc", hdr_crc);
    /* key event */
    FIELD(key_event, "source", source);
    FIELD(key_event, "index", index);
    FIELD(key_event, "event", event);
    FIELD(key_event, "channel", channel);
    FIELD(key_event, "value", value);
    FIELD(key_event, "action", action);
    /* volatile OLED transfer + mode sync; also checked against protocol.json */
    FIELD(oled_stream_chunk, "seq", seq);
    FIELD(oled_stream_chunk, "mode", mode);
    FIELD(oled_stream_chunk, "index", index);
    FIELD(oled_stream_chunk, "count", count);
    FIELD(oled_stream_chunk, "crc32", crc32);
    FIELD(oled_stream_chunk, "pages", pages);
    FIELD(oled_state, "mode", mode);
    FIELD(oled_state, "epoch", epoch);

    /* The last entry has no trailing comma, so close with a sentinel that the
     * JSON reader tolerates: emit a real final field instead. */
    printf("      { \"struct\": \"_meta\", \"name\": \"crcCoveredBytes\", \"offset\": %zu }\n",
           (size_t)CFG_CRC_COVERED_BYTES);
    printf("  ],\n");

    printf("  \"constants\": {\n");
    printf("    \"magicU32\": %u,\n", (unsigned)MAGIC_U32);
    printf("    \"configMagicU32\": %u,\n", (unsigned)MAGIC_CONFIG);
    printf("    \"sectorMagicU32\": %u,\n", (unsigned)MAGIC_SECTOR);
    printf("    \"protocolVersion\": %d,\n", PROTOCOL_VERSION);
    printf("    \"configFormatVersion\": %d,\n", CONFIG_FORMAT_VERSION);
    printf("    \"channels\": %d,\n", CFG_CHANNEL_COUNT);
    printf("    \"keys\": %d,\n", CFG_KEY_COUNT);
    printf("    \"leds\": %d,\n", CFG_LED_COUNT);
    printf("    \"mtu\": %d,\n", CFG_PROTOCOL_MTU);
    printf("    \"textMax\": %d,\n", CFG_TEXT_MAX);
    printf("    \"frameHeaderSize\": %d,\n", FRAME_HEADER_SIZE);
    printf("    \"oledStreamHeaderBytes\": %d,\n", OLED_STREAM_HEADER_BYTES);
    printf("    \"oledStreamChunkBytes\": %d,\n", OLED_STREAM_CHUNK_BYTES);
    printf("    \"oledFrameBytes\": %d,\n", OLED_FRAME_BYTES);
    printf("    \"oledModes\": %d,\n", OLED_SCREEN_COUNT);
    printf("    \"oledStreamTtlMs\": %d,\n", OLED_STREAM_TTL_MS);
    printf("    \"oledStageTimeoutMs\": %d,\n", OLED_STREAM_STAGING_TIMEOUT_MS);
    printf("    \"capOledStream\": %d,\n", CAP_OLED_STREAM);
    printf("    \"capLedOutput\": %d,\n", CAP_LED_OUTPUT);
    printf("    \"statusLedDisabled\": %d,\n", STATUS_LED_DISABLED);
    printf("    \"ledOutputDefault\": %d,\n", BOARD_LED_OUTPUT_ENABLED);
    printf("    \"ledTestHoldMs\": %u,\n", LED_TEST_HOLD_MS);
    printf("    \"cmdOledFrame\": %d,\n", CMD_OLED_FRAME);
    printf("    \"cmdOledFrameAck\": %d,\n", CMD_OLED_FRAME_ACK);
    printf("    \"cmdOledModeEvent\": %d,\n", CMD_OLED_MODE_EVENT);
    printf("    \"frameOverhead\": %d\n", FRAME_OVERHEAD);
    printf("  }\n");
    printf("}\n");
    return 0;
}
