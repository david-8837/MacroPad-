/** Fold a character onto something the font can draw. */
export function glyphFor(ch: string): GlyphRow[] | null {
  if (ch === ' ') return FONT_5X7[' '];
  const upper = ch.toUpperCase();
  if (FONT_5X7[upper]) return FONT_5X7[upper];
  const lower = ch.toLowerCase();
  if (FONT_5X7[lower]) return FONT_5X7[lower];
  return null;
}

/** Rendered width of a string at a given scale, in pixels (no trailing gap). */
export function textWidth(text: string, scale = 1): number {
  if (text.length === 0) return 0;
  return (text.length * GLYPH_ADVANCE - 1) * scale;
}
