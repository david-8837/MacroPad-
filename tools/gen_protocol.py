#!/usr/bin/env python3
"""
gen_protocol.py — emit TypeScript types and a markdown reference from
host/protocol/protocol.json.

Why this exists: protocol.json is the spec, and the spec has three consumers —
the C firmware (checked against it by tests), the JavaScript codec (checked
against it by tests), and eventually your UI. Hand-writing the TS types and the
markdown table means a fourth copy that nothing checks. Generating them means
there are exactly two authoritative artifacts (the C headers and protocol.json),
kept honest by the test suites, and everything else is derived.

    python3 tools/gen_protocol.py

Writes:
    host/protocol/generated/mpad3-protocol.d.ts   types for a TS/Vite UI
    docs/PROTOCOL.md                              human-readable reference

Both files are generated. Edit protocol.json, not them.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "host" / "protocol" / "protocol.json"
OUT_TS = ROOT / "host" / "protocol" / "generated" / "mpad3-protocol.d.ts"
OUT_MD = ROOT / "docs" / "PROTOCOL.md"

# Maps a spec "type" string to a TypeScript type.
TS_TYPE = {
    "u8": "number",
    "u16": "number",
    "u32": "number",
    "i16": "number",
    "bytes": "Uint8Array",
}


def ts_for(field: dict) -> str:
    t = field.get("type", "bytes")
    if t.endswith("]"):  # action[9], channel[3] -> a TS tuple, so length is checked
        base, count = t[:-1].split("[")
        inner = base[0].upper() + base[1:]
        return f"[{', '.join([inner] * int(count))}]"
    if t in ("action", "lighting", "global", "channel", "config"):
        return t[0].upper() + t[1:]
    # A `bytes` field that is really a string in the app's view. The codec takes
    # a JS string and UTF-8 encodes it, so the interface should say string:
    # declaring Uint8Array would make every UI write encode/decode boilerplate.
    if t == "bytes" and field.get("name") == "text":
        return "string"
    # The wire has 27 consecutive RGB bytes; the JS codec exposes nine triples.
    if t == "bytes" and field.get("name") == "perKey":
        return "Array<[number, number, number]>"
    return TS_TYPE.get(t, "number")


def iface_name(struct: str) -> str:
    return struct[0].upper() + struct[1:]


def emit_ts(spec: dict) -> str:
    L: list[str] = []
    w = L.append
    w("// GENERATED by tools/gen_protocol.py from host/protocol/protocol.json.")
    w("// Do not edit. Change the spec and re-run the generator.")
    w("")
    meta = spec["meta"]
    w(f"export const MAGIC_STRING = {json.dumps(meta['magicString'])};")
    w(f"export const MAGIC_U32 = {meta['magicU32']};")
    w(f"export const CONFIG_MAGIC_U32 = {meta['configMagicU32']};")
    w(f"export const SECTOR_MAGIC_U32 = {meta['sectorMagicU32']};")
    w(f"export const PROTOCOL_VERSION = {meta['protocolVersion']};")
    w(f"export const CONFIG_FORMAT_VERSION = {meta['configFormatVersion']};")
    w(f"export const MTU = {meta['mtu']};")
    w(f"export const CHUNK_SIZE = {meta['chunkSize']};")
    w(f"export const CHANNELS = {meta['channels']};")
    w(f"export const KEYS = {meta['keys']};")
    w(f"export const LEDS = {meta['leds']};")
    w(f"export const LED_TEST_HOLD_MS = {meta['ledTestHoldMs']};")
    w(f"export const TEXT_MAX = {meta['textMax']};")
    w(f"export const OLED_MODE_COUNT = {meta['oledModes']};")
    w("export const OLED_STREAM = {")
    for key, field in [("FRAME_BYTES", "oledFrameBytes"),
                       ("CHUNK_BYTES", "oledStreamChunkBytes"),
                       ("CHUNK_COUNT", None),
                       ("HEADER_BYTES", "oledStreamHeaderBytes"),
                       ("STAGING_TIMEOUT_MS", "oledStageTimeoutMs"),
                       ("TTL_MS", "oledStreamTtlMs")]:
        w(f"  {key}: {meta[field] if field else 2},")
    w("} as const;")
    w("")

    # Enums -> SCREAMING_SNAKE const objects plus a union type, so a UI can both
    # write `ACTION_TYPE.TEXT` and iterate the labels to build a dropdown.
    for enum_name, values in spec["enums"].items():
        const_name = re.sub(r"(?<!^)(?=[A-Z])", "_", enum_name).upper()
        # The spec writes enums either as {index: NAME} (actionType) or as
        # {bitmask: NAME} (actionFlag). Both want the same TS shape: NAME -> value.
        pairs = []
        for k, v in values.items():
            value = int(k, 16) if k.lower().startswith("0x") else int(k)
            pairs.append((v, k if k.lower().startswith("0x") else value))
        w(f"export const {const_name} = {{")
        for name, value in pairs:
            w(f"  {name}: {value},")
        w("} as const;")
        w(f"export type {const_name.title().replace('_', '')}Value =")
        w(f"  (typeof {const_name})[keyof typeof {const_name}];")
        w("")

    # Struct interfaces. Field names come straight from the spec, so the TS and
    # the JS codec use identical property names.
    for struct_name, struct in spec["structs"].items():
        w(f"/** {struct['size']} bytes on the wire. */")
        w(f"export interface {iface_name(struct_name)} {{")
        for f in struct["fields"]:
            if f["name"].startswith("pad"):
                continue  # padding is not a field an app should set
            note = f.get("note")
            if note:
                w(f"  /** {note} */")
            w(f"  {f['name']}: {ts_for(f)};")
        w("}")
        w("")

    # The config the app actually edits, spelled out rather than derived, so the
    # UI gets autocomplete on the parts that matter.
    w("/** What a configurator UI holds in memory. Same shape as Channel, but with")
    w(" *  the array lengths spelled out so a UI cannot build a 7-key page. */")
    w("export interface ChannelConfig {")
    w(f"  keys: [{', '.join(['Action'] * int(meta['keys']))}];")
    w("  knobCw: Action;")
    w("  knobCcw: Action;")
    w("  knobTap: Action;")
    w("  knobHold: Action;")
    w("  lighting: Lighting;")
    w("}")
    w("")
    w("export interface DeviceConfig {")
    w("  global: Global;")
    w(f"  channels: [{', '.join(['ChannelConfig'] * int(meta['channels']))}];")
    w("}")
    w("")
    w("export interface Info {")
    for f in spec["payloads"]["info"]["fields"]:
        w(f"  {f['name']}: {ts_for(f)};")
    w("}")
    w("")
    w("export interface KeyEvent {")
    for f in spec["payloads"]["keyEvent"]["fields"]:
        note = f.get("note")
        if note:
            w(f"  /** {note} */")
        w(f"  {f['name']}: {ts_for(f)};")
    w("}")
    w("")
    w("export interface DecodedFrame {")
    w("  cmd: CommandId;")
    w("  payload: Uint8Array;")
    w("  ver: number;")
    w("}")
    w("")
    cmd_vals = " | ".join(str(int(k, 16)) for k in sorted(spec["commands"]))
    w(f"export type CommandId = {cmd_vals};")
    status_vals = " | ".join(str(int(k)) for k in spec["enums"]["status"])
    w(f"export type StatusCode = {status_vals};")
    w("")
    return "\n".join(L) + "\n"


def emit_md(spec: dict) -> str:
    L: list[str] = []
    w = L.append
    meta = spec["meta"]

    w("# mpad3 wire protocol")
    w("")
    w("> **Generated** by `tools/gen_protocol.py` from `host/protocol/protocol.json`.")
    w("> Edit the spec, not this file.")
    w("")
    w(f"Protocol version **{meta['protocolVersion']}**, config format version "
      f"**{meta['configFormatVersion']}**. All integers little-endian.")
    w("")
    w("The transport is USB CDC (a serial port). The device enumerates as a "
      "composite of three interfaces — HID keyboard, HID consumer, and the CDC "
      "port this protocol runs on — so the pad works as a keyboard with nothing "
      "installed, and the configurator is optional.")
    w("")

    w("## Frame")
    w("")
    f = spec["frame"]
    w("```")
    w("offset  size  field")
    w("──────  ────  ─────────────────────────────────────────────")
    frame_type_size = {"u8": 1, "u16": 2, "i16": 2, "u32": 4, "i32": 4}
    for field in f["fields"]:
        length = field.get("length", frame_type_size.get(field["type"], "?"))
        note = f"   {field['note']}" if field.get("note") else ""
        w(f"{str(field['offset']):<7} {str(length):<5} {field['name']}{note}")
    w("```")
    w("")
    crc = f["crc"]
    w(f"**{crc['algorithm']}** — poly `{crc['poly']}`, init `{crc['init']}`, "
      f"no reflection, no final xor. Check value for `\"123456789\"` is "
      f"`{crc['check']}`. It covers {crc['covers']}.")
    w("")
    w("The SOF bytes are *not* covered. They exist only so a receiver that has "
      "lost track can hunt for the next frame; including them in the CRC would "
      "make a corrupt SOF indistinguishable from a corrupt payload and complicate "
      "recovery for no gain.")
    w("")
    w("**Resynchronisation.** The parser is a byte-at-a-time state machine. Any "
      "malformed frame — bad SOF, length over the MTU, wrong version, bad CRC — "
      "is discarded and the parser hunts for the next `A5 5A`. One noisy byte "
      "costs one command, never a replug. A wrong *version* is reported "
      "separately from corruption, after the payload has been consumed, so it "
      "cannot desynchronise the stream.")
    w("")

    w("## Commands")
    w("")
    w("| ID | Name | Direction | Payload | Reply |")
    w("|----|------|-----------|---------|-------|")
    for code, c in sorted(spec["commands"].items()):
        pay = c.get("payload", "—")
        if isinstance(pay, str) and pay != "—":
            pay = f"`{pay}`"
        req = c.get("request") or []
        if req:
            pay = ", ".join(f"`{r['name']}:{r['type']}`" for r in req)
        reply = c.get("response") or "—"
        if reply != "—":
            reply = f"`{reply}`"
        w(f"| `{code}` | **{c['name']}** | {c['dir']} → | {pay} | {reply} |")
    w("")
    for code, c in sorted(spec["commands"].items()):
        if c.get("note"):
            w(f"- **{c['name']}** (`{code}`) — {c['note']}")
    w("")

    if spec.get("oledTransport"):
        w("## Volatile OLED runtime transport")
        w("")
        for para in spec["oledTransport"]:
            w(para)
            w("")

    w("## Structures")
    w("")
    for name, struct in spec["structs"].items():
        w(f"### `{name}` — {struct['size']} bytes")
        w("")
        if struct.get("note"):
            w(struct["note"])
            w("")
        w("| Offset | Size | Field | Notes |")
        w("|-------:|-----:|-------|-------|")
        for field in struct["fields"]:
            t = field["type"]
            if t == "bytes" and field.get("name") == "text":
                t = "utf8 string"
            size = field.get("length")
            if size is None:
                size = {"u8": 1, "u16": 2, "u32": 4, "i16": 2}.get(t, "")
                if t in spec["structs"]:
                    size = spec["structs"][t]["size"]
                if t.endswith("]"):
                    base, count = t[:-1].split("[")
                    size = spec["structs"][base]["size"] * int(count)
            note = field.get("note", "")
            if field.get("enum"):
                note = (f"see [{field['enum']}](#{field['enum'].lower()}) " + note).strip()
            if field.get("value") is not None:
                note = f"always `{field['value']}`. " + note
            if field.get("default") is not None:
                note = f"default `{field['default']}`. " + note
            w(f"| {field['offset']} | {size} | `{field['name']}` | {note.strip()} |")
        w("")
        if struct.get("crc"):
            c = struct["crc"]
            w(f"Checksum: **{c['algorithm']}** over bytes `0..{c['coveredBytes'] - 1}` "
              f"({c['coveredBytes']} bytes), stored at offset {c['coveredBytes']}. "
              f"Reflected poly `{c['reflected']}`, init `{c['init']}`, "
              f"xorout `{c['xorOut']}`; check value for `\"123456789\"` is `{c['check']}`.")
            w("")

    w("## Payloads")
    w("")
    for name, p in spec["payloads"].items():
        w(f"### `{name}` — {p['size']} bytes")
        w("")
        w("| Offset | Field | Type | Notes |")
        w("|-------:|-------|------|-------|")
        for field in p["fields"]:
            w(f"| {field['offset']} | `{field['name']}` | `{field['type']}`"
              f"{'[' + str(field['length']) + ']' if field.get('length') else ''} "
              f"| {field.get('note', '')} |")
        w("")

    w("## Enumerations")
    w("")
    for enum_name, values in spec["enums"].items():
        w(f"### {enum_name}")
        w("")
        w("| Value | Name |")
        w("|-------|------|")
        for k, v in values.items():
            w(f"| `{k}` | `{v}` |")
        w("")
        note = spec.get("enumNotes", {}).get(enum_name)
        if note:
            for para in note:
                w(para)
                w("")

    w("## Physical layout")
    w("")
    lay = spec["layout"]
    w("Key indices, which is also LED indices — LED *n* sits under key *n*, so a "
      "per-key effect is a one-line lookup rather than a mapping table.")
    w("")
    # Widths are computed, not typed. Hardcoded box-drawing widths are how the
    # earlier version of this diagram came out ragged the moment a GPIO number
    # changed from one digit to two (K7 moved from GP26 to GP11 and back).
    w("```")
    rows = [[k for k in lay["keys"] if k.get("row", k["index"] // 3) == r]
            for r in range(3)]
    text = [[f"K{k['index']} GP{k['gpio']}" for k in row] for row in rows]
    cw = max(len(c) for row in text for c in row) + 2   # one space of padding each side
    bar = "─" * cw
    w(" " * (3 + cw + 1) + "┌───────┐")
    w(" " * (3 + cw + 1) + "│ knob  │  encoder A/B/switch; long-press = change channel")
    w("   ┌" + bar + "┬" + bar + "┬" + bar + "┐")
    for i, row in enumerate(text):
        w("   │" + "│".join(c.center(cw) for c in row) + "│")
        if i < 2:
            w("   ├" + bar + "┼" + bar + "┼" + bar + "┤")
    w("   └" + bar + "┴" + bar + "┴" + bar + "┘")
    w("```")
    w("")
    b = lay.get("board", {})
    if b:
        w(f"**{b['name']}** — {b['mcu']}, {b['ram']} RAM, {b['flash']} flash.")
        w("")
        w(f"- Header: {b['headerPins']}.")
        w(f"- {b['notOnMainHeader']}.")
        w(f"- Numbering: {b['headerNumbering']}.")
        w(f"- Spare after this map: {b['spareHeaderGpio']}.")
        w(f"- Saved config lives at {b['configSectors']}.")
        w("")
    w("| Function | GPIO | Header pin | LED |")
    w("|----------|-----:|-----------:|----:|")
    for k in lay["keys"]:
        w(f"| Key K{k['index']} | GP{k['gpio']} | {k['headerPin']} | LED {k['index']} |")
    enc = lay["encoder"]
    w(f"| Encoder A | GP{enc['a']['gpio']} | {enc['a']['headerPin']} | — |")
    w(f"| Encoder B | GP{enc['b']['gpio']} | {enc['b']['headerPin']} | — |")
    w(f"| Encoder switch | GP{enc['switch']['gpio']} | {enc['switch']['headerPin']} | — |")
    led = lay["leds"]["data"]
    w(f"| LED data | GP{led['gpio']} | {led['headerPin']} | {lay['leds']['count']} LEDs, {lay['leds']['order']} |")
    w("")
    w(lay["ledIndexNote"])
    w("")

    w("## Typical exchange")
    w("")
    chunks = (spec['structs']['config']['size'] + meta['chunkSize'] - 1) // meta['chunkSize']
    last = chunks - 1
    w("```")
    w("host                          device")
    w("  PING            ──────────▶")
    w("                  ◀──────────  PONG")
    w("  GET_INFO        ──────────▶")
    w(f"                  ◀──────────  INFO   ({meta['channels']} channels, {meta['keys']} keys, {meta['leds']} LED slots on full / 0 physical LEDs on keys-only, {spec['structs']['config']['size']}-byte config)")
    w("  GET_CONFIG 0    ──────────▶")
    w(f"                  ◀──────────  CONFIG_CHUNK (0/{chunks})")
    w("       ⋮               ⋮              ⋮")
    w(f"  GET_CONFIG {last}    ──────────▶")
    w(f"                  ◀──────────  CONFIG_CHUNK ({last}/{chunks}, short)")
    w("")
    w(f"  SET_CONFIG 0..{last} ──────────▶   (streamed; applied to RAM when chunk {last} lands)")
    w("                  ◀──────────  SET_ACK / ERROR")
    w("  COMMIT          ──────────▶   (~50 ms: erase + program one 4 KiB sector)")
    w("                  ◀──────────  COMMIT_ACK")
    w("")
    w("                  ◀──────────  KEY_EVENT  (unsolicited, while usbReportEvents=1)")
    w("```")
    w("")
    w("Note that `SET_CONFIG` alone changes what the pad does but not what survives a "
      f"power cycle. `COMMIT` is separate on purpose: a UI that streams {chunks} chunks "
      f"should trigger **one** flash erase, not {chunks}, and a user who previews a "
      "binding and hates it should be able to walk away without it being written.")
    w("")
    return "\n".join(L) + "\n"


def main() -> int:
    if not SPEC.exists():
        print(f"spec not found: {SPEC}", file=sys.stderr)
        return 1
    if any(arg != "--check" for arg in sys.argv[1:]):
        print("usage: python3 tools/gen_protocol.py [--check]", file=sys.stderr)
        return 2
    spec = json.loads(SPEC.read_text())
    generated = {OUT_TS: emit_ts(spec), OUT_MD: emit_md(spec)}

    if "--check" in sys.argv[1:]:
        stale = [p for p, content in generated.items() if not p.exists() or p.read_text() != content]
        if stale:
            for p in stale:
                print(f"stale generated protocol file: {p.relative_to(ROOT)}", file=sys.stderr)
            return 1
        print("generated protocol types and documentation match the spec")
        return 0

    for path, content in generated.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
